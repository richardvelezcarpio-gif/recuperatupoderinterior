BEGIN;

CREATE SCHEMA rpi_private;
REVOKE ALL ON SCHEMA rpi_private FROM PUBLIC, anon, authenticated, service_role;

CREATE TABLE rpi_private.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    email TEXT COLLATE "C" NOT NULL,
    password_hash TEXT NOT NULL,
    marketing BIGINT NOT NULL DEFAULT 0,
    -- Conserva texto, nulabilidad y formato UTC original de SQLite.
    created_at TEXT DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT users_email_key UNIQUE (email)
);

CREATE TABLE rpi_private.sessions (
    token_hash TEXT COLLATE "C",
    user_id BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    CONSTRAINT sessions_pkey PRIMARY KEY (token_hash),
    CONSTRAINT sessions_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES rpi_private.users(id) ON UPDATE NO ACTION ON DELETE NO ACTION
);

CREATE TABLE rpi_private.program_starts (
    user_id BIGINT,
    started_at BIGINT NOT NULL,
    CONSTRAINT program_starts_pkey PRIMARY KEY (user_id),
    CONSTRAINT program_starts_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES rpi_private.users(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT program_starts_started_at_check CHECK (started_at >= 0)
);

CREATE TABLE rpi_private.program_answers (
    user_id BIGINT NOT NULL,
    day BIGINT NOT NULL,
    reflection TEXT NOT NULL,
    questions TEXT NOT NULL,
    exercise TEXT NOT NULL,
    completed BIGINT NOT NULL DEFAULT 0,
    updated_at BIGINT NOT NULL,
    CONSTRAINT program_answers_pkey PRIMARY KEY (user_id, day),
    CONSTRAINT program_answers_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES rpi_private.users(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT program_answers_day_check CHECK (day BETWEEN 1 AND 7),
    CONSTRAINT program_answers_completed_check CHECK (completed IN (0, 1))
);

-- Los PRIMARY KEY y UNIQUE crean cinco índices B-tree automáticamente:
-- users_pkey, users_email_key, sessions_pkey,
-- program_starts_pkey, program_answers_pkey.
-- Las definiciones SQLite revisadas no declaran índices adicionales.
-- No se añade CHECK de marketing ni validación JSON: no existían en origen.
-- PostgreSQL exige token_hash NOT NULL por ser PK; SQLite permite NULL en
-- PK de texto. El backend siempre genera su hash. Verificar esta condición
-- antes de importar; abortar si existen anomalías, nunca descartar filas.

-- Defensa adicional: ningún acceso de los roles usados por la Data API.
REVOKE ALL ON ALL TABLES IN SCHEMA rpi_private FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA rpi_private FROM PUBLIC, anon, authenticated, service_role;
ALTER TABLE rpi_private.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE rpi_private.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE rpi_private.program_starts ENABLE ROW LEVEL SECURITY;
ALTER TABLE rpi_private.program_answers ENABLE ROW LEVEL SECURITY;
-- Sin políticas: roles ordinarios sin acceso. El propietario postgres puede
-- operar mediante conexión privada. Un futuro rol backend necesitará diseño
-- explícito de permisos/RLS; no concederlo a anon/authenticated/service_role.

COMMIT;

