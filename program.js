export const DAY_MS = 24 * 60 * 60 * 1000;
// El reloj solo se inyecta desde código en las pruebas, nunca mediante peticiones.
export function mountProgram(app, {db, getUser, now = Date.now, allowedOrigins = new Set()}) {
  const answerRow = db.prepare('SELECT reflection,questions,exercise,completed,updated_at FROM program_answers WHERE user_id=? AND day=?');
  const saveAnswers = db.prepare(`INSERT INTO program_answers(user_id,day,reflection,questions,exercise,completed,updated_at) VALUES(?,?,?,?,?,?,?)
    ON CONFLICT(user_id,day) DO UPDATE SET reflection=excluded.reflection,questions=excluded.questions,exercise=excluded.exercise,
    completed=GREATEST(program_answers.completed,excluded.completed),updated_at=excluded.updated_at`);
  async function answers(userId, day) {
    const row = await answerRow.get(userId, day);
    return row ? {...row, questions: JSON.parse(row.questions), completed: Boolean(row.completed), updated_at: new Date(row.updated_at).toISOString()}
      : {reflection:'', questions:['','',''], exercise:'', completed:false, updated_at:null};
  }
  const completed = db.prepare('SELECT day FROM program_answers WHERE user_id=? AND completed=1 ORDER BY day');
  const read = db.prepare('SELECT started_at FROM program_starts WHERE user_id=?');
  const insert = db.prepare('INSERT INTO program_starts(user_id,started_at) VALUES(?,?) ON CONFLICT(user_id) DO NOTHING');
  async function status(userId, time = now()) {
    const row = await read.get(userId);
    const availableDays = row ? Math.min(7, Math.max(0, Math.floor((time - row.started_at) / DAY_MS) + 1)) : 0;
    const next = row && availableDays < 7 ? row.started_at + availableDays * DAY_MS : null;
    return {
      completedDays: (await completed.all(userId)).map(row => row.day),
      startedAt: row ? new Date(row.started_at).toISOString() : null,
      serverTime: new Date(time).toISOString(), availableDays,
      nextUnlockAt: next === null ? null : new Date(next).toISOString(),
      remainingMs: next === null ? null : Math.max(0, next - time)
    };
  }
  app.use('/api/program', async (req, res, next) => {
    res.set('Cache-Control', 'no-store');
    const user = await getUser(req);
    if (!user) return res.status(401).json({error: 'Inicia sesión para acceder al programa.'});
    if (['POST','PUT','DELETE'].includes(req.method) &&
        (!req.is('application/json') || req.get('Sec-Fetch-Site') === 'cross-site' ||
         !allowedOrigins.has(req.get('Origin')) ||
         req.rawHeaders.filter((value, index) => index % 2 === 0 && value.toLowerCase() === 'origin').length !== 1)) {
      return res.status(403).json({error:'Realiza esta acción desde la página del programa.'});
    }
    req.programUserId = user.id;
    next();
  });
  app.get('/api/program/status', async (req, res) => res.json(await status(req.programUserId)));
  app.post('/api/program/start', async (req, res) => {
    const time = now();
    await insert.run(req.programUserId, time);
    res.json(await status(req.programUserId, time));
  });
  async function availableDay(req, res, next) {
    if (!/^[1-7]$/.test(req.params.day)) return res.status(400).json({error: 'Día no válido.'});
    req.programDay = Number(req.params.day);
    const state = await status(req.programUserId);
    if (req.programDay > state.availableDays) return res.status(403).json({error: state.startedAt ? 'Este día todavía está bloqueado.' : 'Comienza el programa para abrir el día 1.', ...state});
    next();
  }
  app.get('/api/program/days/:day', availableDay, async (req, res) => {
    const day = req.programDay;
    res.json({day, ...content[day - 1], questions:content[day - 1].questions || [content[day - 1].question, '¿Qué has observado en ti?', '¿Qué pequeño paso quieres dar?'], answers:await answers(req.programUserId, day)});
  });
  function store(completing) {
    return async (req, res) => {
      const body = req.body;
      const text = value => typeof value === 'string' && value.length <= 500;
      if (!body || Array.isArray(body) || Object.keys(body).some(key => !['reflection','questions','exercise'].includes(key)) ||
          !text(body.reflection) || !text(body.exercise) || !Array.isArray(body.questions) || body.questions.length !== 3 || !body.questions.every(text)) {
        return res.status(400).json({error:'Incluye una reflexión, tres respuestas y el ejercicio, con un máximo de 500 caracteres por campo.'});
      }
      await saveAnswers.run(req.programUserId, req.programDay, body.reflection, JSON.stringify(body.questions), body.exercise, Number(completing), now());
      res.json({ok:true, answers:await answers(req.programUserId,req.programDay)});
    };
  }
  app.put('/api/program/days/:day/answers', availableDay, store(false));
  app.post('/api/program/days/:day/complete', availableDay, store(true));
  app.delete('/api/program/days/:day/answers', availableDay, async (req, res) => {
    await db.prepare('DELETE FROM program_answers WHERE user_id=? AND day=?').run(req.programUserId, req.programDay);
    res.json({ok:true, answers:await answers(req.programUserId,req.programDay)});
  });
}
